#!/bin/bash
# Check that the library agrees with lean/Challenge.lean, the way Lean comparator will judge it.
# Usage: tools/challenge_check.sh check
#
# Challenge.lean imports nothing of the library: it holds a copy of every library declaration the target statements use,
# under the same names, and the target statements (stages/2-statements.md §4). The script
#  1. refuses a Challenge.lean that imports a module of the library;
#  2. starting from the theorems of Challenge.lean, collects every declaration of the library they use, through the
#     types of all of them and the values of definitions, once under `Challenge` and once under `TargetsCheck` (which
#     imports the library's target modules), and compares kind, type, value and universe parameters of each;
#  3. reports any of them that is private (comparator cannot match a private name across modules), and prints the
#     axioms of the targets in the library.
# Comparing elaborated terms, not source text, also catches a change hidden behind a private definition, an instance
# or a notation. Needs up-to-date .olean files of Challenge and TargetsCheck, so run it after a passing build.
# Exit 0: they agree. Exit 3: a declaration differs, is missing, is private, or Challenge imports the library.
# Exit 2: setup problem.
set -u
source "$(dirname "$0")/sheaf_env.sh"
[ "${1:-}" = check ] || { echo "usage: tools/challenge_check.sh check"; exit 2; }
C="$SHEAF_LEAN/Challenge.lean"; [ -f "$C" ] || { echo "No lean/Challenge.lean yet: nothing to check."; exit 0; }
ROOTS=($SHEAF_LIB TargetsCheck)
BAD=$(grep -oP '^(?:public\s+)?(?:meta\s+)?import\s+(?:all\s+)?\K[\w.]+' "$C" | while read -r m; do
  for r in "${ROOTS[@]}"; do [ "${m%%.*}" = "$r" ] && echo "$m"; done; done)
if [ -n "$BAD" ]; then
  echo "lean/Challenge.lean imports the library; it must import only Mathlib and copy what it needs:"; echo "$BAD"; exit 3
fi
D="$SHEAF_LEAN/.sandbox/_sheaf"; mkdir -p "$D"
# side, module roots that count as ours on that side, and the names to start from (empty: the theorems of Challenge)
script() {
  local side=$1 roots=$2 start=$3
  cat <<LEAN
import Lean
import $side
open Lean in
#eval show CoreM Unit from do
  let env ← getEnv
  let roots : List Name := [$roots]
  let ours (n : Name) : Bool := match env.getModuleIdxFor? n with
    | some i => roots.contains env.header.moduleNames[i]!.getRoot
    | none => false
  let mut todo : Array Name := #[$start]
  if todo.isEmpty then
    for (n, c) in env.constants.toList do
      if let .thmInfo _ := c then
        -- written in Challenge.lean, not generated by Lean (a structure's injEq has no declaration range)
        if !n.isInternal && (env.getModuleIdxFor? n).any (env.header.moduleNames[·]! == \`Challenge)
            && (← findDeclarationRanges? n).isSome then
          todo := todo.push n
  for n in todo do IO.println s!"START {n}"
  let starts := todo
  let mut seen : NameSet := {}
  while h : 0 < todo.size do
    let n := todo.back
    todo := todo.pop
    if seen.contains n then continue
    seen := seen.insert n
    let some c := env.find? n | IO.println s!"DECL {n} MISSING"; continue
    if !starts.contains n && !ours n then continue
    if isPrivateName n then IO.println s!"PRIVATE {n}"
    let mut used := c.type.getUsedConstants
    let mut kind := "other"
    let mut value := "-"
    match c with
    | .defnInfo v => kind := "def"; value := toString (hash v.value); used := used ++ v.value.getUsedConstants
    | .opaqueInfo v => kind := "opaque"; value := toString (hash v.value); used := used ++ v.value.getUsedConstants
    | .thmInfo _ => kind := "theorem"
    | .axiomInfo _ => kind := "axiom"
    | .inductInfo v => kind := s!"inductive {v.ctors}"; used := used ++ v.ctors.toArray
    | .ctorInfo v => kind := "constructor"; used := used.push v.induct
    | .recInfo _ => kind := "recursor"
    | .quotInfo _ => kind := "quot"
    IO.println s!"DECL {n} {kind} {hash c.type} {value} {c.levelParams}"
    todo := todo ++ used
LEAN
}
quote() { local out="" x; for x in "$@"; do out+="\`$x, "; done; echo "${out%, }"; }
script Challenge "\`Challenge" "" > "$D/Check_Challenge.lean"
A=$("$(dirname "$0")/lean_file.sh" "$D/Check_Challenge.lean" 2>&1) || { echo "$A"; exit 2; }
mapfile -t NAMES < <(echo "$A" | grep -oP '^START \K\S+')
[ ${#NAMES[@]} -gt 0 ] || { echo "No theorems in lean/Challenge.lean"; exit 2; }
script TargetsCheck "$(quote $SHEAF_LIB)" "$(quote "${NAMES[@]}")" > "$D/Check_TargetsCheck.lean"
for n in "${NAMES[@]}"; do echo "#print axioms $n"; done >> "$D/Check_TargetsCheck.lean"
B=$(SHEAF_FILE_TIMEOUT=${SHEAF_FILE_TIMEOUT:-300} "$(dirname "$0")/lean_file.sh" "$D/Check_TargetsCheck.lean" 2>&1) || { echo "$B"; exit 2; }
echo "$B" | grep -v -e '^DECL' -e '^START' -e '^PRIVATE' -e '^Compiled in'
FAIL=0
P=$( (echo "$A"; echo "$B") | grep '^PRIVATE' | sort -u)
if [ -n "$P" ]; then
  echo "Private declarations used by the target statements (make them public, stages/2-statements.md §4):"; echo "$P"; FAIL=1
fi
if [ "$(echo "$A" | grep '^DECL' | sort)" != "$(echo "$B" | grep '^DECL' | sort)" ]; then
  echo "The library differs from lean/Challenge.lean (< Challenge, > library):"
  diff <(echo "$A" | grep '^DECL' | sort) <(echo "$B" | grep '^DECL' | sort); FAIL=1
fi
[ $FAIL = 0 ] || exit 3
echo "The library agrees with lean/Challenge.lean: ${#NAMES[@]} theorems, $(echo "$A" | grep -c '^DECL') declarations compared."
